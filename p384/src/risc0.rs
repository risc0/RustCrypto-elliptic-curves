use risc0_bigint2::ec::{Curve, WeierstrassCurve};
use risc0_bigint2::field::FIELD_384_WIDTH_WORDS;

/// The secp384r1 curve's prime field characteristic
/// p = 2^384 - 2^128 - 2^96 + 2^32 - 1
pub(crate) const SECP384R1_PRIME: [u32; FIELD_384_WIDTH_WORDS] = [
    0xFFFFFFFF, 0x00000000, 0x00000000, 0xFFFFFFFF, 0xFFFFFFFE, 0xFFFFFFFF, 
    0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF,
];

/// The secp384r1 curve's order
pub(crate) const SECP384R1_ORDER: [u32; FIELD_384_WIDTH_WORDS] = [
    0xCCC52973, 0xECEC196A, 0x48B0A77A, 0x581A0DB2, 0xF4372DDF, 0xC7634D81, 
    0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF,
];

pub(crate) const SECP384R1_EQUATION_A_LE: [u32; FIELD_384_WIDTH_WORDS] = [
    0xFFFFFFFC, 0x00000000, 0x00000000, 0xFFFFFFFF, 0xFFFFFFFE, 0xFFFFFFFF,
    0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF,
];

pub(crate) const SECP384R1_EQUATION_B_LE: [u32; FIELD_384_WIDTH_WORDS] = [
    0xD3EC2AEF, 0x2A85C8ED, 0x8A2ED19D, 0xC656398D, 0x5013875A, 0x0314088F,
    0xFE814112, 0x181D9C6E, 0xE3F82D19, 0x988E056B, 0xE23EE7E4, 0xB3312FA7,
];

const SECP384R1_CURVE: &WeierstrassCurve<FIELD_384_WIDTH_WORDS> =
    &WeierstrassCurve::<FIELD_384_WIDTH_WORDS>::new(
        SECP384R1_PRIME,
        // Curve parameter a = -3 (represented mod p)
        SECP384R1_EQUATION_A_LE,
        SECP384R1_EQUATION_B_LE,
    );

impl Curve<FIELD_384_WIDTH_WORDS> for crate::NistP384 {
    const CURVE: &'static WeierstrassCurve<FIELD_384_WIDTH_WORDS> = SECP384R1_CURVE;
}
